namespace
{
	void AppendU16 (std::string &s, uint16_t v)
	{
		s += (char) (v & 0xFF);
		s += (char) ((v >> 8) & 0xFF);
	}

	void AppendU32 (std::string &s, uint32_t v)
	{
		s += (char) (v & 0xFF);
		s += (char) ((v >> 8) & 0xFF);
		s += (char) ((v >> 16) & 0xFF);
		s += (char) ((v >> 24) & 0xFF);
	}

	// Builds a minimal one-entry STORED zip. The data itself is always
	// "AAAA" (4 bytes); nCompSize/nUncompSize in both headers are
	// whatever the caller passes, so a mismatched pair can be built.
	std::string BuildStoredZip (uint32_t nCompSize, uint32_t nUncompSize)
	{
		const char *pName = "x";
		const uint16_t nNameLen = 1;
		const char Data[4] = {'A', 'A', 'A', 'A'};
		const uint32_t nCRC = 0xD019F413u;	// deliberately wrong (real CRC-32 of "AAAA" is 0x9b0d08f1)

		std::string Zip;

		size_t nLocalOffset = Zip.size ();
		AppendU32 (Zip, 0x04034B50u);	// local file header signature
		AppendU16 (Zip, 20);		// version needed
		AppendU16 (Zip, 0);		// flags
		AppendU16 (Zip, 0);		// method: stored
		AppendU16 (Zip, 0);		// mod time
		AppendU16 (Zip, 0);		// mod date
		AppendU32 (Zip, nCRC);
		AppendU32 (Zip, nCompSize);
		AppendU32 (Zip, nUncompSize);
		AppendU16 (Zip, nNameLen);
		AppendU16 (Zip, 0);		// extra length
		Zip += pName;
		Zip.append (Data, sizeof Data);

		size_t nCDOffset = Zip.size ();
		AppendU32 (Zip, 0x02014B50u);	// central directory signature
		AppendU16 (Zip, 20);		// version made by
		AppendU16 (Zip, 20);		// version needed
		AppendU16 (Zip, 0);		// flags
		AppendU16 (Zip, 0);		// method: stored
		AppendU16 (Zip, 0);		// mod time
		AppendU16 (Zip, 0);		// mod date
		AppendU32 (Zip, nCRC);
		AppendU32 (Zip, nCompSize);
		AppendU32 (Zip, nUncompSize);
		AppendU16 (Zip, nNameLen);
		AppendU16 (Zip, 0);		// extra length
		AppendU16 (Zip, 0);		// comment length
		AppendU16 (Zip, 0);		// disk number start
		AppendU16 (Zip, 0);		// internal attributes
		AppendU32 (Zip, 0);		// external attributes
		AppendU32 (Zip, (uint32_t) nLocalOffset);
		Zip += pName;
		size_t nCDSize = Zip.size () - nCDOffset;

		AppendU32 (Zip, 0x06054B50u);	// EOCD signature
		AppendU16 (Zip, 0);		// disk number
		AppendU16 (Zip, 0);		// disk with CD
		AppendU16 (Zip, 1);		// entries on this disk
		AppendU16 (Zip, 1);		// total entries
		AppendU32 (Zip, (uint32_t) nCDSize);
		AppendU32 (Zip, (uint32_t) nCDOffset);
		AppendU16 (Zip, 0);		// comment length

		return Zip;
	}
}

TEST (ZipExtractStoredSizeMismatchRejected)
{
	// A STORED entry's uncompressed size must equal its compressed size.
	// Claiming a larger uncompressed size (as a corrupted or malicious
	// zip could) must not read past the bytes the format actually has.
	std::string Zip = BuildStoredZip (4, 100);

	uint8_t Buf[256];
	size_t  nOut = 0;
	TZipResult r = ZipExtract ((const uint8_t *) Zip.data (), Zip.size (),
	                          "x", Buf, sizeof Buf, &nOut);
	CHECK_EQ (r, (int) ZipInvalidFormat);
}

TEST (ZipExtractStoredMatchingSizeWorks)
{
	// Sanity check: BuildStoredZip() itself produces an extractable entry
	// when the sizes do match (CRC is wrong on purpose, so expect that).
	std::string Zip = BuildStoredZip (4, 4);

	uint8_t Buf[256];
	size_t  nOut = 0;
	TZipResult r = ZipExtract ((const uint8_t *) Zip.data (), Zip.size (),
	                          "x", Buf, sizeof Buf, &nOut);
	CHECK_EQ (r, (int) ZipCRCError);
}
