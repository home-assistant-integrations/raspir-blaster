// ----- helpers ------------------------------------------------------------------

static std::string InflateStr (const uint8_t *pIn, size_t nIn)
{
	std::string out (65536, '\0');
	size_t nOut = 0;
	TInflateResult r = Inflate (pIn, nIn,
	                            (uint8_t *) &out[0], out.size (), &nOut);
	if (r != InflateOK)
		return std::string ();
	out.resize (nOut);
	return out;
}

static std::string ZipStr (const uint8_t *pZip, size_t nZip, const char *pName)
{
	std::string out (65536, '\0');
	size_t nOut = 0;
	TZipResult r = ZipExtract (pZip, nZip, pName,
	                           (uint8_t *) &out[0], out.size (), &nOut);
	if (r != ZipOK)
		return std::string ();
	out.resize (nOut);
	return out;
}

// Load a file into a vector-like buffer
static std::string LoadFile (const char *pPath)
{
	FILE *f = fopen (pPath, "rb");
	if (!f)
		return std::string ();
	fseek (f, 0, SEEK_END);
	long n = ftell (f);
	fseek (f, 0, SEEK_SET);
	if (n <= 0) { fclose (f); return std::string (); }
	std::string buf ((size_t) n, '\0');
	fread (&buf[0], 1, (size_t) n, f);
	fclose (f);
	return buf;
}

